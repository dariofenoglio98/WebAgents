"""Refresh or check the generated parts of the WebAir package and its example tasks.

    cd demo/webair
    .venv/bin/python -m publisher sync    # rewrite the generated files from the origin
    .venv/bin/python -m publisher check   # exit 1 if any of them differs from the origin now

Generated: `agents/webair/schemas/api/*.json` (WebAir's published API contract),
`agents/webair/schemas/host/*.json` (the demo host's resource type schemas, which the
package must declare exactly), `agents/webair/fixtures/workflow.json` (the package's
recorded fixture: searches only, no personal data), the example tasks
`examples/webair-*.json`, `examples/webair-capability-scenarios.json` (the host-owned
capability demo's tasks, grants, picks, model scripts and WebAir's answers),
`examples/webair-site.json` (the origin's own HTML pages, which offline website-discovery
fixtures serve) and `demo/webair/host-bindings.json` (the demo host's operator bindings of
the four WebAir tools to the public origin). Everything else in `agents/webair/` (manifest,
graph, policy, tool declarations, skills, package-authored schemas) is written by hand, and
the contract tests check it against the origin.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from .capabilities import capability_document
from .contract import PACKAGE_SOURCE, REPO_ROOT, contract_files
from .fixture import FIXTURE_PATH, record_fixture, source_files
from .host import host_schema_files
from .host_bindings import HOST_BINDINGS, host_bindings_document
from .scenarios import capability_scenario, scenario, scenarios
from .site import capture_site

EXAMPLES = REPO_ROOT / "examples"


def example_files(current: dict[str, bytes]) -> dict[Path, dict]:
    """Task inputs for the README commands, and every scenario with what it must yield."""
    return {
        EXAMPLES / "webair-input.json": scenario("hero").input,
        EXAMPLES / "webair-booking-input.json": capability_scenario("booking").input,
        EXAMPLES / "webair-purchase-input.json": capability_scenario("purchase-visa").input,
        EXAMPLES / "webair-capability-scenarios.json": capability_document(current),
        EXAMPLES / "webair-scenarios.json": {
            "profile": "webair-demo-scenarios-v0",
            "package_id": "org.webagents.webair",
            "note": "Inputs and expected outcomes of the package fixture's scenarios: searches "
            "only, so the signed fixture holds no personal data. Generated by "
            "demo/webair/publisher.",
            "scenarios": [
                {"id": s.id, "summary": s.summary, "input": s.input, "expect": s.expect}
                for s in scenarios()
            ],
        },
        EXAMPLES / "webair-site.json": capture_site(),
    }


def generated() -> dict[Path, dict]:
    contract = {**contract_files(), **host_schema_files()}
    # Record the fixture against the schemas the origin and the host publish now.
    current = {
        **source_files(),
        **{path: json.dumps(doc).encode() for path, doc in contract.items()},
    }
    documents = {PACKAGE_SOURCE / path: doc for path, doc in contract.items()}
    documents[PACKAGE_SOURCE / FIXTURE_PATH] = record_fixture(current)
    current[FIXTURE_PATH] = json.dumps(documents[PACKAGE_SOURCE / FIXTURE_PATH]).encode()
    documents.update(example_files(current))
    # The demo host's operator configuration for the four WebAir tools (not package content).
    documents[HOST_BINDINGS] = host_bindings_document()
    return documents


def render(document: dict) -> str:
    return json.dumps(document, indent=2, ensure_ascii=False) + "\n"


def drift() -> list[str]:
    stale = []
    for path, document in generated().items():
        if not path.is_file() or json.loads(path.read_text()) != document:
            stale.append(path.relative_to(REPO_ROOT).as_posix())
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m publisher", description=__doc__.split("\n")[0])
    parser.add_argument("command", choices=["sync", "check"])
    args = parser.parse_args(argv)
    if args.command == "check":
        stale = drift()
        print(json.dumps({"stale": stale}, indent=2))
        return 1 if stale else 0
    for path, document in generated().items():
        path.write_text(render(document))
        print(f"wrote {path.relative_to(REPO_ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
